/**
 * Проверки разбора чека (assets/receipt.js) на настоящих формах строк.
 *
 * Запуск: node test/receipt.mjs
 *
 * Здесь важнее не «сколько распознали», а «не выдумали ли лишнего»: строка
 * ИТОГО, попавшая в позиции, удваивает счёт, а ИНН, принятый за цену, добавляет
 * к ужину семь миллионов. Поэтому в каждом наборе проверяется и то, что должно
 * было отсеяться.
 */
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const { parseReceipt } = require(path.resolve(fileURLToPath(import.meta.url), "../../assets/receipt.js"));

let failures = 0;
function ok(name, cond, extra = "") {
  console.log(`${cond ? "  OK  " : " FAIL "} ${name}${extra ? " — " + extra : ""}`);
  if (!cond) failures++;
}
const asPairs = r => r.items.map(i => `${i.title}=${i.amount}`).join(" | ");

/* ---------- 1. Чек кафе с количеством и итогами ---------- */
{
  const r = parseReceipt(`ООО "Чайхана Джума"
ИНН 7701234567
Чайник улун 2 x 445,00  890,00
Хачапури по-аджарски 620.00
Салат из огурцов — 340 ₽
Лимонад домашний 3 х 180 540,00
ИТОГО: 2390,00
Картой 2390,00`);
  ok("позиции кафе разобраны", asPairs(r) === "Чайник улун=890 | Хачапури по-аджарски=620 | Салат из огурцов=340 | Лимонад домашний=540", asPairs(r));
  ok("сумма позиций сходится с чеком", r.items.reduce((s, i) => s + i.amount, 0) === 2390);
  ok("количество разобрано", r.items[0].qty === 2 && r.items[3].qty === 3);
}

/* ---------- 2. Служебные строки не попадают в позиции ---------- */
{
  const r = parseReceipt(`ИТОГО 1000,00
Всего к оплате 1000
НДС 20% 166,67
Сдача 0,00
ИНН 123456789012
ФН 9999078900012345
Чек № 42
Кассир Иванова А.
Смена 15
Тел +7 900 123-45-67`);
  ok("служебные строки отброшены целиком", r.items.length === 0, asPairs(r));
}

/* ---------- 3. Разные способы записи цены ---------- */
{
  const r = parseReceipt(`Кофе 180
Чай 180,5
Пирог 1 250,00
Вода...............90
Суп — 320 руб
Десерт 450 ₽`);
  ok("форматы цен разобраны", asPairs(r) === "Кофе=180 | Чай=180.5 | Пирог=1250 | Вода=90 | Суп=320 | Десерт=450", asPairs(r));
}

/* ---------- 4. Латиница и заграничный чек ---------- */
{
  const r = parseReceipt(`Khinkali 8 x 1.50 12.00
Wine glass 7.50
Total 19.50`);
  ok("латинский чек разобран", asPairs(r) === "Khinkali=12 | Wine glass=7.5", asPairs(r));
}

/* ---------- 5. Мусор не превращается в позиции ---------- */
{
  const r = parseReceipt(`2
шт
=====
1234567890123456
`);
  ok("строки без названия отброшены", r.items.length === 0, asPairs(r));
}

/* ---------- 6. Настоящий чек ресторана ----------
   Гостевой счёт «Пряничного кота»: колонка «Кол-во», разбивка по гостям,
   перенос длинных названий на вторую строку и итог по каждому гостю.
   Ровно тот случай, на котором прежний разбор давал кашу. */
{
  // Так строки выглядят после распознавания: широкие пробелы между колонками
  // размечены табуляцией (см. assets/ocr.js).
  const scanned = [
    "Онлайн-касса",
    "АТОЛ",
    "Пряничный Кот - ООО \"Фудсервис\"",
    "ИНН",
    "ГОСТЕВОЙ СЧЕТ",
    "Зал: Зал Общий\tСтол: 10",
    "Открыт: 01.08.2026 11:47\tЗаказ № 107",
    "Официант: Сальцова Александра_1760",
    "Наименование\tКол-во\tСумма",
    "Гость 1",
    "Завтрак Папа может\t1\t790.00",
    "Сырники с вареньем из Владимирск\t1\t490.00",
    "ой вишни",
    "Итого к оплате Гость 1:\t1 280.00",
    "Гость 2",
    "Флет-Уайт\t1\t350.00",
    "Завтрак Папа может\t1\t790.00",
    "Чизкейк Сан-Себастьян шт\t1\t370.00",
    "Итого к оплате Гость 2:\t1 510.00",
    "Гость 3",
    "Тропический Смузи\t1\t400.00",
    "Английский завтрак\t1\t620.00",
    "Штрудель яблочный-апельсиновый ш\t1\t350.00",
    "т",
    "Итого к оплате Гость 3:\t1 370.00",
    "Гость 4",
    "Завтрак Папа может\t1\t790.00",
    "Рулет меренговый с фисташками и\t1\t450.00",
    "малиновым пюре шт",
    "Итого к оплате Гость 4:\t1 240.00",
    "Гость 5",
    "Английский завтрак\t1\t620.00",
    "Штрудель яблочный-апельсиновый ш\t1\t350.00",
    "т",
    "Лимонад Апельсин-Имбирь 1.0 л\t1\t890.00",
    "Итого к оплате Гость 5:\t1 860.00",
    "Итого по предприятиям с учетом скидок/надбавок:",
    "Сумма по ООО\t4 500.00",
    "Сумма по ИП\t2 760.00",
    "ИТОГО К ОПЛАТЕ:\t7 260.00",
    "СберЧаевые",
    "Отсканируйте QR-код",
  ].join("\n");

  const r = parseReceipt(scanned);
  const total = r.items.reduce((s, i) => s + i.amount, 0);
  ok("настоящий чек: 13 позиций", r.items.length === 13, `${r.items.length}: ${asPairs(r)}`);
  ok("настоящий чек: сумма сходится с «ИТОГО К ОПЛАТЕ»", total === 7260, String(total));
  ok("колонка «Кол-во» не слиплась с суммой", r.items[0].amount === 790 && r.items[0].qty === 1,
    JSON.stringify(r.items[0]));
  ok("перенесённое название склеено", r.items[1].title === "Сырники с вареньем из Владимирской вишни",
    r.items[1].title);
  ok("перенос одной буквы склеен", r.items.some(i => i.title === "Штрудель яблочный-апельсиновый шт"),
    r.items.filter(i => i.title.startsWith("Штрудель")).map(i => i.title).join(" / "));
  ok("перенос словами склеен через пробел",
    r.items.some(i => i.title === "Рулет меренговый с фисташками и малиновым пюре шт"),
    r.items.filter(i => i.title.startsWith("Рулет")).map(i => i.title).join(" / "));
  ok("итоги по гостям и предприятиям отброшены", !r.items.some(i => /итого|сумма по/i.test(i.title)), asPairs(r));
  ok("шапка чека отброшена", !r.items.some(i => /зал|стол|заказ|официант|инн/i.test(i.title)), asPairs(r));
  ok("цена внутри названия не съела сумму",
    r.items.some(i => i.title === "Лимонад Апельсин-Имбирь 1.0 л" && i.amount === 890),
    r.items.filter(i => i.title.startsWith("Лимонад")).map(i => `${i.title}=${i.amount}`).join(" / "));
}

/* ---------- 7. Тот же чек без разметки колонок ----------
   Так выглядит текст, вставленный руками. Колонку количества здесь не видно
   по расстояниям, поэтому её вычисляем по чеку целиком. */
{
  const plain = `Наименование Кол-во Сумма
Гость 1
Завтрак Папа может 1 790.00
Сырники с вареньем 1 490.00
Итого к оплате Гость 1: 1 280.00
Гость 2
Флет-Уайт 1 350.00
Чизкейк Сан-Себастьян шт 1 370.00
Итого к оплате Гость 2: 1 510.00
ИТОГО К ОПЛАТЕ: 7 260.00`;
  const r = parseReceipt(plain);
  ok("вставленный текст: количество распознано как колонка",
    asPairs(r) === "Завтрак Папа может=790 | Сырники с вареньем=490 | Флет-Уайт=350 | Чизкейк Сан-Себастьян шт=370",
    asPairs(r));
}

/* ---------- 8. Пустой ввод ---------- */
{
  const r = parseReceipt("");
  ok("пустой текст — пустой результат", r.items.length === 0 && r.skipped === 0);
}

console.log(failures ? `\nПровалено проверок: ${failures}` : "\nРазбор чека: всё сошлось.");
process.exit(failures ? 1 : 0);
