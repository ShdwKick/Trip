/**
 * Проверки разбора чека (assets/receipt.js) на настоящих формах строк.
 *
 * Запуск: node test/receipt.mjs
 *
 * Здесь важнее не «сколько распознали», а «не выдумали ли лишнего»: строка
 * ИТОГО, попавшая в позиции, удваивает счёт, а ИНН, принятый за цену, добавляет
 * к ужину семь миллионов. Поэтому в каждом наборе проверяется и то, что должно
 * было отсеяться.
 */
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const { parseReceipt } = require(path.resolve(fileURLToPath(import.meta.url), "../../assets/receipt.js"));

let failures = 0;
function ok(name, cond, extra = "") {
  console.log(`${cond ? "  OK  " : " FAIL "} ${name}${extra ? " — " + extra : ""}`);
  if (!cond) failures++;
}
const asPairs = r => r.items.map(i => `${i.title}=${i.amount}`).join(" | ");

/* ---------- 1. Чек кафе с количеством и итогами ---------- */
{
  const r = parseReceipt(`ООО "Чайхана Джума"
ИНН 7701234567
Чайник улун 2 x 445,00  890,00
Хачапури по-аджарски 620.00
Салат из огурцов — 340 ₽
Лимонад домашний 3 х 180 540,00
ИТОГО: 2390,00
Картой 2390,00`);
  ok("позиции кафе разобраны", asPairs(r) === "Чайник улун=890 | Хачапури по-аджарски=620 | Салат из огурцов=340 | Лимонад домашний=540", asPairs(r));
  ok("сумма позиций сходится с чеком", r.items.reduce((s, i) => s + i.amount, 0) === 2390);
  ok("количество разобрано", r.items[0].qty === 2 && r.items[3].qty === 3);
}

/* ---------- 2. Служебные строки не попадают в позиции ---------- */
{
  const r = parseReceipt(`ИТОГО 1000,00
Всего к оплате 1000
НДС 20% 166,67
Сдача 0,00
ИНН 123456789012
ФН 9999078900012345
Чек № 42
Кассир Иванова А.
Смена 15
Тел +7 900 123-45-67`);
  ok("служебные строки отброшены целиком", r.items.length === 0, asPairs(r));
}

/* ---------- 3. Разные способы записи цены ---------- */
{
  const r = parseReceipt(`Кофе 180
Чай 180,5
Пирог 1 250,00
Вода...............90
Суп — 320 руб
Десерт 450 ₽`);
  ok("форматы цен разобраны", asPairs(r) === "Кофе=180 | Чай=180.5 | Пирог=1250 | Вода=90 | Суп=320 | Десерт=450", asPairs(r));
}

/* ---------- 4. Латиница и заграничный чек ---------- */
{
  const r = parseReceipt(`Khinkali 8 x 1.50 12.00
Wine glass 7.50
Total 19.50`);
  ok("латинский чек разобран", asPairs(r) === "Khinkali=12 | Wine glass=7.5", asPairs(r));
}

/* ---------- 5. Мусор не превращается в позиции ---------- */
{
  const r = parseReceipt(`2
шт
=====
1234567890123456
`);
  ok("строки без названия отброшены", r.items.length === 0, asPairs(r));
}

/* ---------- 6. Пустой ввод ---------- */
{
  const r = parseReceipt("");
  ok("пустой текст — пустой результат", r.items.length === 0 && r.skipped === 0);
}

console.log(failures ? `\nПровалено проверок: ${failures}` : "\nРазбор чека: всё сошлось.");
process.exit(failures ? 1 : 0);
